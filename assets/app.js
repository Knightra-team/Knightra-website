function applyLanguage(lang) {
  const dict = translations[lang] || translations.en;
  document.documentElement.lang = lang === 'fa' ? 'fa' : 'en';
  document.documentElement.dir = lang === 'fa' ? 'rtl' : 'ltr';
  document.body.classList.toggle('rtl', lang === 'fa');
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (dict[key] !== undefined) el.placeholder = dict[key];
  });
  document.querySelectorAll('[data-lang-label]').forEach(el => {
    el.textContent = lang === 'fa' ? dict.lang_fa : dict.lang_en;
  });
  document.querySelectorAll('.language-option').forEach(el => {
    el.classList.toggle('active', el.dataset.lang === lang);
  });
  localStorage.setItem('Knightra-lang', lang);
}

function init() {
  const saved = localStorage.getItem('Knightra-lang') || 'en';
  applyLanguage(saved);

  document.querySelectorAll('[data-set-lang]').forEach(btn => {
    btn.addEventListener('click', () => applyLanguage(btn.dataset.setLang));
  });

  const menuBtn = document.querySelector('.menu-toggle');
  const mobileMenu = document.querySelector('.mobile-menu');
  if (menuBtn && mobileMenu) {
    menuBtn.addEventListener('click', () => {
      mobileMenu.classList.toggle('open');
      menuBtn.setAttribute('aria-expanded', mobileMenu.classList.contains('open'));
    });
  }

  document.querySelectorAll('.mobile-menu a').forEach(a => a.addEventListener('click', () => mobileMenu?.classList.remove('open')));

  const form = document.querySelector('#contactForm');
  const msg = document.querySelector('#formSuccess');
  if (form && msg) {
    form.addEventListener('submit', e => {
      e.preventDefault();
      const lang = document.documentElement.lang === 'fa' ? 'fa' : 'en';
      msg.textContent = translations[lang].success_msg;
      msg.classList.add('show');
      form.reset();
    });
  }

  const year = document.querySelector('[data-year]');
  if (year) year.textContent = new Date().getFullYear();
}

document.addEventListener('DOMContentLoaded', init);
